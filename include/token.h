#ifndef MILK_TOKEN_H
#define MILK_TOKEN_H

typedef enum {
TOKEN_EOF,
TOKEN_NEWLINE,
TOKEN_INDENT,
TOKEN_DEDENT,

TOKEN_IDENTIFIER,
TOKEN_NUMBER,
TOKEN_STRING,

TOKEN_ARROW,
TOKEN_LEFT_PAREN,
TOKEN_RIGHT_PAREN,
TOKEN_LEFT_BRACKET,
TOKEN_RIGHT_BRACKET,
TOKEN_COMMA,

TOKEN_PLUS,
TOKEN_MINUS,
TOKEN_STAR,
TOKEN_SLASH,
TOKEN_PERCENT,

TOKEN_EQUAL_EQUAL,
TOKEN_NOT_EQUAL,
TOKEN_LESS,
TOKEN_LESS_EQUAL,
TOKEN_GREATER,
TOKEN_GREATER_EQUAL,

TOKEN_SHOW,
TOKEN_RUN,
TOKEN_CHECK,
TOKEN_OTHERWISE,
TOKEN_REPEAT,
TOKEN_DURING,
TOKEN_MAKE,
TOKEN_GIVE,

TOKEN_YES,
TOKEN_NO,
TOKEN_EMPTY

} TokenType;

typedef struct {
TokenType type;
const char *start;
int length;
int line;
int column;
int indent;
} Token;

#endif
